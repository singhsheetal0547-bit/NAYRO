package com.example.ui.workspace

import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.testTag
import androidx.compose.ui.unit.dp
import com.example.core.workspace.WorkspaceFileItem
import com.example.core.workspace.WorkspaceManager
import com.example.ui.theme.ForestGreen

@Composable
fun WorkspaceScreen(
    workspaceManager: WorkspaceManager,
    modifier: Modifier = Modifier
) {
    var files by remember { mutableStateOf(workspaceManager.listWorkspaceFiles()) }
    var selectedFileContent by remember { mutableStateOf<String?>(null) }
    var newReportTitle by remember { mutableStateOf("") }
    var statusMessage by remember { mutableStateOf("") }

    Column(
        modifier = modifier
            .fillMaxSize()
            .padding(16.dp)
            .testTag("workspace_screen")
    ) {
        Text(
            text = "Persistent Workspace",
            style = MaterialTheme.typography.headlineSmall,
            color = ForestGreen
        )
        Text(
            text = "File Explorer, Research Artifacts, Extracted Documents & Workspace Code.",
            style = MaterialTheme.typography.bodyMedium,
            color = MaterialTheme.colorScheme.onSurfaceVariant
        )

        Spacer(modifier = Modifier.height(14.dp))

        // Create Artifact Action Card
        Card(
            shape = RoundedCornerShape(12.dp),
            colors = CardDefaults.cardColors(containerColor = ForestGreen.copy(alpha = 0.08f)),
            modifier = Modifier.fillMaxWidth()
        ) {
            Column(modifier = Modifier.padding(12.dp)) {
                Text("Create Research Artifact", style = MaterialTheme.typography.titleSmall, color = ForestGreen)
                Spacer(modifier = Modifier.height(6.dp))
                OutlinedTextField(
                    value = newReportTitle,
                    onValueChange = { newReportTitle = it },
                    label = { Text("Report Title") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth().testTag("artifact_title_input")
                )
                Spacer(modifier = Modifier.height(6.dp))
                Button(
                    onClick = {
                        if (newReportTitle.isNotBlank()) {
                            val msg = workspaceManager.createReportArtifact(newReportTitle, "Report content generated by Babu Agent for '$newReportTitle'.")
                            statusMessage = msg
                            newReportTitle = ""
                            files = workspaceManager.listWorkspaceFiles()
                        }
                    },
                    colors = ButtonDefaults.buttonColors(containerColor = ForestGreen),
                    modifier = Modifier.align(Alignment.End).testTag("save_artifact_btn")
                ) {
                    Text("Save Artifact")
                }
            }
        }

        if (statusMessage.isNotBlank()) {
            Spacer(modifier = Modifier.height(6.dp))
            Text(text = statusMessage, style = MaterialTheme.typography.labelSmall, color = ForestGreen)
        }

        Spacer(modifier = Modifier.height(14.dp))
        Text(text = "Workspace Files (${files.size})", style = MaterialTheme.typography.titleMedium, color = ForestGreen)
        Spacer(modifier = Modifier.height(8.dp))

        LazyColumn(
            verticalArrangement = Arrangement.spacedBy(8.dp),
            modifier = Modifier.fillMaxSize()
        ) {
            items(files) { file ->
                Card(
                    shape = RoundedCornerShape(10.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.4f)),
                    modifier = Modifier.fillMaxWidth().testTag("workspace_file_${file.name}")
                ) {
                    Row(
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween,
                        modifier = Modifier.fillMaxWidth().padding(12.dp)
                    ) {
                        Column(modifier = Modifier.weight(1f)) {
                            Text(text = file.name, style = MaterialTheme.typography.titleSmall, color = ForestGreen)
                            Text(text = "${file.sizeBytes} bytes • ${file.path}", style = MaterialTheme.typography.labelSmall)
                        }
                        Button(
                            onClick = {
                                selectedFileContent = workspaceManager.readWorkspaceFile(file.name)
                            },
                            colors = ButtonDefaults.buttonColors(containerColor = ForestGreen)
                        ) {
                            Text("Read", style = MaterialTheme.typography.labelSmall)
                        }
                    }
                }
            }
        }

        selectedFileContent?.let { content ->
            AlertDialog(
                onDismissRequest = { selectedFileContent = null },
                title = { Text("File Preview") },
                text = { Text(content, style = MaterialTheme.typography.bodySmall) },
                confirmButton = {
                    TextButton(onClick = { selectedFileContent = null }) {
                        Text("Close")
                    }
                }
            )
        }
    }
}
